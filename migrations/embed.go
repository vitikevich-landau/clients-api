// Package migrations встраивает SQL-миграции прямо в исполняемый файл.
//
// # Почему embed, а не чтение файлов с диска
//
// Бинарник получается самодостаточным: его можно скопировать куда угодно
// или положить в scratch-контейнер без единого лишнего файла — миграции
// уже внутри. Не бывает ситуации "выкатили новую версию сервиса,
// а папку migrations забыли положить рядом".
//
// Директива //go:embed работает только с файлами в СВОЁМ каталоге
// или ниже — подняться к родителю (../) нельзя. Поэтому этот файл
// лежит именно здесь, рядом с .sql.
package migrations

import "embed"

// FS — файловая система с SQL-миграциями, вшитая в бинарник на этапе сборки.
//
//go:embed *.sql
var FS embed.FS
