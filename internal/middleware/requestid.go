package middleware

import (
	"github.com/gin-gonic/gin"
	"github.com/google/uuid"
)

// RequestID присваивает каждому запросу уникальный идентификатор.
//
// # Зачем это нужно
//
// Пользователь пишет «у меня ошибка». Без request_id остаётся гадать,
// какой из тысяч запросов в логах его. С request_id — один поиск,
// и видна вся цепочка: маршрут, решение авторизации, SQL-ошибка, ответ.
//
// Идентификатор:
//   - кладётся в gin.Context (доступен хендлерам);
//   - подмешивается в логгер, поэтому попадает в КАЖДУЮ строчку лога
//     этого запроса автоматически;
//   - возвращается клиенту в заголовке X-Request-ID, чтобы человек
//     мог сообщить его в поддержку.
//
// # Почему сначала смотрим входящий заголовок
//
// Если перед нами стоит nginx/Envoy или запрос пришёл от другого нашего
// сервиса, идентификатор уже сгенерирован выше. Подхватив его, мы получаем
// сквозную трассировку через всю цепочку сервисов. Сгенерировав свой,
// мы бы эту цепочку разорвали.
func RequestID() gin.HandlerFunc {
	return func(c *gin.Context) {
		requestID := c.GetHeader(HeaderRequestID)

		if !isValidRequestID(requestID) {
			// Не пришёл или пришёл мусор — генерируем свой.
			requestID = uuid.NewString()
		}

		// Кладём в контекст gin — отсюда его возьмут логгер и хендлеры.
		c.Set(ctxKeyRequestID, requestID)

		// Возвращаем клиенту. Заголовок ставим ДО c.Next():
		// после того как хендлер начал писать тело ответа,
		// заголовки уже отправлены и менять их поздно.
		c.Writer.Header().Set(HeaderRequestID, requestID)

		c.Next()
	}
}

// maxRequestIDLen — потолок длины принимаемого идентификатора.
const maxRequestIDLen = 128

// isValidRequestID проверяет пришедший снаружи идентификатор.
//
// # Почему нельзя просто доверять заголовку
//
// Значение попадёт в логи и в ответ клиенту. Если пропустить туда что угодно:
//
//   - перевод строки ломает построчный разбор логов, и злоумышленник
//     может ПОДДЕЛАТЬ лишние строки в журнале (log injection);
//   - мегабайтная строка раздувает каждую запись лога;
//   - управляющие символы ломают вывод в терминале.
//
// Поэтому пропускаем только безопасный набор: буквы, цифры, дефис,
// подчёркивание, точка.
func isValidRequestID(s string) bool {
	if s == "" || len(s) > maxRequestIDLen {
		return false
	}

	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z':
		case r >= 'A' && r <= 'Z':
		case r >= '0' && r <= '9':
		case r == '-' || r == '_' || r == '.':
		default:
			return false
		}
	}

	return true
}
