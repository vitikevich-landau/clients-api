package logger

import (
	"context"
	"log/slog"
)

// ctxKey — приватный тип ключа для context.WithValue.
//
// ПОЧЕМУ СВОЙ ТИП, А НЕ ПРОСТО СТРОКА "logger":
// context — общее пространство имён для всего процесса. Если два пакета
// положат значение по строковому ключу "logger", один затрёт другой,
// и отладка превратится в ад. Приватный тип, объявленный в этом пакете,
// физически не может совпасть с ключом из другого пакета.
type ctxKey struct{}

// ToContext кладёт логгер в контекст.
//
// Смысл всей затеи: в самом начале обработки запроса middleware создаёт
// логгер, в который УЖЕ ВШИТЫ request_id, метод и путь. Дальше любой слой
// (service, repository) достаёт логгер из контекста и просто пишет —
// а все эти поля добавляются в каждую запись автоматически.
//
// Результат: все строчки лога от одного запроса помечены одним request_id.
// Расследование инцидента превращается в один поиск вместо часа гадания.
func ToContext(ctx context.Context, l *slog.Logger) context.Context {
	return context.WithValue(ctx, ctxKey{}, l)
}

// FromContext достаёт логгер из контекста.
//
// Если логгера там нет (например, вызов из теста или из фонового кода,
// не связанного с HTTP-запросом) — возвращаем slog.Default(),
// чтобы вызывающий код никогда не получил nil и не словил панику.
func FromContext(ctx context.Context) *slog.Logger {
	if l, ok := ctx.Value(ctxKey{}).(*slog.Logger); ok && l != nil {
		return l
	}
	return slog.Default()
}
